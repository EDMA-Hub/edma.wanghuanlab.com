export const products = Object.fromEntries(productList.map((item) => [item.slug, item]))

export const allProducts = productList

export function familyById(id) {
  return families.find((item) => item.id === id)
}

export function productsInFamily(familyId) {
  const family = familyById(familyId)
  return family ? family.slugs.map((slug) => products[slug]) : []
}

export function relatedProducts(slug) {
  const product = products[slug]
  if (!product) return []
  return product.related.map((item) => products[item]).filter(Boolean)
}

export function searchProducts(keyword) {
  const needle = keyword.trim().toLowerCase()
  if (!needle) return allProducts
  return allProducts.filter((item) => {
    const blob = `${item.code} ${item.name} ${item.fullName} ${item.tagline} ${item.modules.map((module) => module.name).join(' ')}`
    return blob.toLowerCase().includes(needle)
  })
}
